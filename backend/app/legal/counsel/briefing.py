""""What matters today?" — a briefing from the matter's own records (docs/echomind-legal/04 Journey B).

Nothing here is generated by the model. Each item is a record the person may open, counted or named as it is:
- potential inconsistencies still unresolved (discrepancies.py), most important first;
- AI drafts and exports in this matter waiting for the person's decision (the existing reviews queue);
- documents added since the person's last briefing on this matter, and how many are still being read;
- deadlines proposed from the documents that no lawyer has confirmed yet (obligations; never set by the model);
- when two or more documents have not been checked against each other yet, the offer to check them.

At most three items are shown (the most important first), the rest counted behind "Show more". When there is
nothing, the briefing says so, with the time of the last one.
"""
from __future__ import annotations

from typing import Optional
from urllib.parse import quote as urlquote

from ...core.db import get_conn
from ..documents import repo as doc_repo
from ..compare import scan
from . import discrepancies, schemas, store

NEW_WINDOW_DAYS = 14            # never briefed on this matter: documents added in this window count as new


def _since_default() -> str:
    from datetime import datetime, timedelta, timezone
    return (datetime.now(timezone.utc) - timedelta(days=NEW_WINDOW_DAYS)).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def _when(iso: Optional[str]) -> str:
    return (iso or "")[:16].replace("T", " ") + (" UTC" if iso else "")


def _valid(action: dict) -> bool:
    try:
        schemas.Action.model_validate(action)
        return True
    except Exception:
        return False


def build(principal: dict, matter: dict) -> tuple[dict, list[str]]:
    """The priority_list props and the document ids it names. Marks the briefing as seen."""
    uid, mid, number = principal["sub"], matter["id"], matter["number"]
    base = f"/m/{urlquote(number, safe='')}"
    seen = store.last_seen(uid, mid)
    since = seen or _since_default()
    items: list[dict] = []
    named_docs: list[str] = []

    open_rows = discrepancies.listed(principal, mid)
    if open_rows:
        top = open_rows[0]
        a, b = top["detail"]["a"], top["detail"]["b"]
        named_docs += [top["document_a_id"], top["document_b_id"]]
        more = f" and {len(open_rows) - 1} more" if len(open_rows) > 1 else ""
        items.append({"id": "discrepancies", "kind": "discrepancy",
                      "title": f"{len(open_rows)} potential inconsistenc{'y' if len(open_rows) == 1 else 'ies'} to review",
                      "detail": f"{a.get('document_title')} says “{a.get('value')}”; {b.get('document_title')} says “{b.get('value')}”{more}.",
                      "action": {"id": "review", "label": "Review", "action_type": "open_discrepancy", "target_id": top["id"]}})

    from ..reviews import queue
    waiting = [w for w in queue.for_principal(principal)["waiting"] if (w.get("matter") or {}).get("number") == number]
    if waiting:
        w = waiting[0]
        action = {"id": "open_review", "label": "Open", "action_type": "open_page", "path": w["path"]}
        if _valid(action):
            items.append({"id": "reviews", "kind": "review",
                          "title": f"{len(waiting)} item{'s' if len(waiting) != 1 else ''} waiting for your review",
                          "detail": f"{w['title']}" + (f", from {w['by']}" if w.get("by") else "") + ".", "action": action})

    docs = doc_repo.list_documents(mid, uid)
    new = [d for d in docs if (d.get("created_at") or "") > since]
    if new:
        reading = sum(1 for d in new if (d.get("current_version") or {}).get("index_status") in ("queued", "indexing"))
        ready = [d for d in new if (d.get("current_version") or {}).get("index_status") == "indexed"]
        named_docs += [d["id"] for d in new[:3]]
        names = ", ".join(d["title"] for d in new[:3]) + (f" and {len(new) - 3} more" if len(new) > 3 else "")
        detail = names + (f". {reading} still being read." if reading else ".")
        action = ({"id": "summarize_new", "label": "What do they say?", "action_type": "ask",
                   "prompt": "Summarize the key points of the new documents.", "document_ids": [d["id"] for d in ready[:10]]}
                  if ready else {"id": "open_documents", "label": "Open documents", "action_type": "open_page", "path": f"{base}/documents"})
        items.append({"id": "new_documents", "kind": "new_documents",
                      "title": f"{len(new)} new document{'s' if len(new) != 1 else ''} since {'your last briefing' if seen else 'the last two weeks'}",
                      "detail": detail, "action": action})

    with get_conn() as conn:
        proposed = conn.execute("SELECT COUNT(*), MIN(due_date) FROM legal_obligations o WHERE o.matter_id=? AND o.status='proposed' "
                                f"AND EXISTS (SELECT 1 FROM legal_documents d WHERE d.id = o.document_id AND {doc_repo.VISIBLE_TO})",
                                (mid, uid)).fetchone()
    if proposed and proposed[0]:
        items.append({"id": "obligations", "kind": "obligation",
                      "title": f"{proposed[0]} deadline{'s' if proposed[0] != 1 else ''} proposed from the documents, not yet confirmed",
                      "detail": ("Earliest proposed date " + proposed[1] + ". " if proposed[1] else "")
                                + "Dates are not set until a lawyer confirms them.",
                      "action": {"id": "open_obligations", "label": "Confirm dates", "action_type": "open_page", "path": f"{base}/obligations"}})

    if not open_rows:
        scanned = scan.documents(mid, uid, "signed")
        if len(scanned) >= 2 and not discrepancies.already_scanned(mid, discrepancies.versions_sha(scanned)):
            items.append({"id": "scan", "kind": "scan", "title": f"{len(scanned)} documents not yet checked against each other",
                          "detail": "Look for dates, amounts and terms that the documents state differently.",
                          "action": {"id": "scan", "label": "Check now", "action_type": "ask",
                                     "prompt": "Find conflicting facts in the documents."}})

    store.mark_seen(uid, mid)
    shown, rest = items[:schemas.MAX_PRIORITY_ITEMS], items[schemas.MAX_PRIORITY_ITEMS:]
    if shown:
        summary = (f"{len(items)} thing{'s' if len(items) != 1 else ''} in {number} "
                   f"need{'s' if len(items) == 1 else ''} your attention.")
        props = {"summary": summary, "items": shown, "more": len(rest)}
    else:
        when = f" since {_when(seen)}" if seen else ""
        props = {"summary": f"Nothing new in the {number} records you can see{when}.", "items": [], "more": 0,
                 "empty": f"Nothing new in the records you can see{when}."}
    return props, sorted(set(named_docs))
